"""Turn the server's ``server-info.json`` into importable client profiles.

Deliberately emitters, not templates: JSON via ``json.dumps`` and the mihomo
config as a hand-written block —— no template engine, so the tool stays
stdlib-only and the output is diffable.
"""

from __future__ import annotations

import base64
import json
import os
from typing import Any
from urllib.parse import quote

from . import state

