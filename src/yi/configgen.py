def render_singbox(info: dict[str, Any], label: str = "HK-Spot") -> str:
    """sing-box 1.11+ schema (tun + mixed inbounds, VLESS/REALITY outbound)."""
    payload = {
        "log": {"level": "info", "timestamp": True},
        "dns": {
            "servers": [
                {"tag": "dns-remote", "address": "https://1.1.1.1/dns-query", "detour": "proxy"},
                {"tag": "dns-direct", "address": "223.5.5.5", "detour": "direct"},
            ],
            "rules": [{"ip_is_private": True, "server": "dns-direct"}],
        },
        "inbounds": [
            {
                "type": "tun",
                "tag": "tun-in",
                "address": ["172.19.0.1/30"],
                "mtu": 1500,
                "auto_route": True,
                "strict_route": True,
                "stack": "mixed",
                "sniff": True,
            },
            {
                "type": "mixed",
                "tag": "mixed-in",
                "listen": "127.0.0.1",
                "listen_port": 7891,
                "sniff": True,
            },
        ],
        "outbounds": [
            {
                "type": "vless",
                "tag": "proxy",
                "server": info["address"],
                "server_port": int(info["port"]),
                "uuid": info["uuid"],
                "packet_encoding": "xudp",
                "tls": {
                    "enabled": True,
                    "server_name": info.get("sni") or "www.microsoft.com",
                    "utls": {"enabled": True, "fingerprint": info.get("fingerprint") or "chrome"},
                    "reality": {
                        "enabled": True,
                        "public_key": info["public_key"],
                        "short_id": info.get("short_id") or "",
                    },
                },
            },
            {"type": "direct", "tag": "direct"},
        ],
        "route": {
            "rules": [
                {"action": "sniff"},
                {"protocol": "dns", "action": "hijack-dns"},
                {"ip_is_private": True, "outbound": "direct"},
            ],
            "final": "proxy",
            "auto_detect_interface": True,
        },
        "experimental": {"cache_file": {"enabled": True, "store_fakeip": True}},
    }
    if info.get("flow"):
        payload["outbounds"][0]["flow"] = info["flow"]
    return json.dumps(payload, indent=2, ensure_ascii=False) + "\n"


