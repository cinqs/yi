def write_profiles(info: dict[str, Any], label: str = "HK-Spot") -> dict[str, str]:
    """Write every client artifact into $YI_HOME/profiles and return the paths."""
    root = state.profiles_dir()
    os.makedirs(root, mode=0o700, exist_ok=True)
    link = build_link(info, label)
    artifacts = {
        "vless-link.txt": link + "\n",
        "v2rayng-subscription.txt": subscription_blob([link]) + "\n",
        "mihomo.yaml": render_mihomo(info, label),
        "singbox.json": render_singbox(info, label),
        "README.txt": render_readme(info, label),
    }
    paths: dict[str, str] = {}
    for name, content in artifacts.items():
        path = os.path.join(root, name)
        state.write_private(path, content, 0o600)
        paths[name] = path
    return paths
