def build_link(info: dict[str, Any], label: str = "HK-Spot") -> str:
    params = [
        ("encryption", "none"),
        ("flow", info.get("flow") or ""),
        ("security", info.get("security") or "reality"),
        ("sni", info.get("sni") or "www.microsoft.com"),
        ("fp", info.get("fingerprint") or "chrome"),
        ("pbk", info["public_key"]),
        ("sid", info.get("short_id") or ""),
        ("type", info.get("transport") or "tcp"),
        ("headerType", "none"),
    ]
    pairs = ["{}={}".format(key, quote(str(value), safe="")) for key, value in params if value != ""]
    return "vless://{}@{}:{}?{}#{}".format(
        info["uuid"],
        info["address"],
        int(info["port"]),
        "&".join(pairs),
        quote(label, safe=""),
    )


def subscription_blob(links: list[str]) -> str:
    """v2rayNG/Clash style subscription payload: base64 of newline-joined links."""
    return base64.b64encode(("\n".join(links) + "\n").encode("utf-8")).decode("ascii")


